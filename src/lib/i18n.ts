export const DICTIONARIES: Record<Lang, Record<MessageKey, string>> = { sl, en };

export type Params = Record<string, string | number>;

/** Translate with {placeholder} interpolation; falls back to Slovenian, then to the key. */
export function translate(lang: Lang, key: MessageKey, params?: Params): string {
  const raw = DICTIONARIES[lang]?.[key] ?? DICTIONARIES.sl[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

